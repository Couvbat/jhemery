/** Anything the table doesn't know renders as `?` rather than vanishing. */
function glyph(char: string): string[] {
  return FONT[char] ?? FONT[FALLBACK]!
}

/** Splits into chunks that fit the buffer width, breaking on spaces where it can. */
function chunk(text: string, maxChars: number): string[] {
  const out: string[] = []
  let rest = text

  while (rest.length > maxChars) {
    const window = rest.slice(0, maxChars + 1)
    const space = window.lastIndexOf(' ')
    // A word longer than a whole line has to be cut mid-word; anything else
    // breaks at the last space that fits.
    const cut = space > 0 ? space : maxChars
    out.push(rest.slice(0, cut))
    rest = rest.slice(space > 0 ? cut + 1 : cut)
  }
  if (rest.length) out.push(rest)

  return out
}

/**
 * Renders `text` as block letters. Returns plain strings — the caller decides
 * the tone and whether they're `pre`.
 *
 * Long input wraps into stacked blocks separated by a blank line, rather than
 * running off the right edge of the buffer.
 */
export function bannerLines(
  text: string,
  { maxChars = BANNER_MAX_CHARS, on = '█', off = ' ' } = {},
): string[] {
  const normalised = text.toUpperCase().replace(/\s+/g, ' ').trim()
  if (!normalised) return []

  const out: string[] = []
  for (const piece of chunk(normalised, maxChars)) {
    if (out.length) out.push('')
    const glyphs = [...piece].map(glyph)
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      const line = glyphs
        .map((g) => g[row]!.replaceAll('#', on).replaceAll('.', off))
        .join(off)
      // Trailing blanks are invisible but make copied output ragged.
      out.push(line.replace(/\s+$/, ''))
    }
  }
  return out
}
